//! Fixed-layout wgpu-hal 30.0.2 DX12/FXC contract (DX12 code identical to 30.0.1). Video generation is independent.
use naga::{ShaderStage, back::hlsl, valid::Validator};
use naga_wgpu as naga;
use std::{fmt::Write as _, path::Path};

pub fn generate(fxc: Option<&Path>) {
    println!("cargo:rerun-if-changed=build/still_image_shaders.rs");
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    let mut table = String::from("// Generated by build.rs; do not edit.\n");
    for (family, path, textures) in [
        ("NIS", "src/gpu_nis.wgsl", 1),
        ("ANIME4K_VL", "src/gpu_anime4k.wgsl", 14),
    ] {
        println!("cargo:rerun-if-changed={path}");
        let source = std::fs::read_to_string(path).expect("read static-image WGSL");
        let module = naga::front::wgsl::parse_str(&source).expect("parse static-image WGSL");
        let info = Validator::new(
            naga::valid::ValidationFlags::all(),
            naga::valid::Capabilities::all(),
        )
        .validate(&module)
        .expect("validate static-image WGSL");
        let options = options(textures);
        let fragments = module
            .entry_points
            .iter()
            .filter(|ep| ep.stage == ShaderStage::Fragment)
            .map(|ep| ep.name.as_str())
            .collect::<Vec<_>>();
        assert_eq!(fragments.len(), if textures == 1 { 1 } else { 18 });
        // Both variants are embedded: root egui-wgpu uses from_build_config().with_env(),
        // so WGPU_DEBUG must retain the HAL's DEBUG/SKIP_OPTIMIZATION semantics too.
        for debug in [false, true] {
            let suffix = if debug { "DEBUG" } else { "RELEASE" };
            writeln!(
                table,
                "const {family}_{suffix}: BytecodeSet = BytecodeSet {{"
            )
            .unwrap();
            for (index, entry) in std::iter::once("vs_main")
                .chain(fragments.iter().copied())
                .enumerate()
            {
                let stage = if index == 0 {
                    ShaderStage::Vertex
                } else {
                    ShaderStage::Fragment
                };
                let (hlsl_source, reflected) =
                    translate(&module, &info, &options, stage, entry, fragments[0]);
                if stage == ShaderStage::Vertex {
                    // Sharing a VS is valid only while every FS has the same
                    // linkage. Refuse a future interface change at build time.
                    for fragment in &fragments[1..] {
                        assert_eq!(
                            translate(&module, &info, &options, stage, entry, fragment),
                            (hlsl_source.clone(), reflected.clone()),
                            "{family}: cannot share VS across {fragment} linkage",
                        );
                    }
                }
                let stem = format!("still_{family}_{suffix}_{entry}");
                let hlsl_path = out.join(format!("{stem}.hlsl"));
                std::fs::write(&hlsl_path, hlsl_source).unwrap();
                if let Some(fxc) = fxc {
                    let target = if stage == ShaderStage::Vertex {
                        "vs_5_1"
                    } else {
                        "ps_5_1"
                    };
                    let mut command = std::process::Command::new(fxc);
                    // compile_fxc: ENABLE_STRICTNESS, plus DEBUG|SKIP_OPTIMIZATION
                    // only for InstanceFlags::DEBUG. Default O1, never video's /O3.
                    command.args(["/nologo", "/Ges", "/T", target, "/E", &reflected]);
                    if debug {
                        command.args(["/Zi", "/Od"]);
                    }
                    let result = command
                        .arg("/Fo")
                        .arg(out.join(format!("{stem}.cso")))
                        .arg(&hlsl_path)
                        .output()
                        .expect("run Windows SDK FXC");
                    assert!(
                        result.status.success(),
                        "FXC {stem}: {}{}",
                        String::from_utf8_lossy(&result.stdout),
                        String::from_utf8_lossy(&result.stderr)
                    );
                }
                let blob = format!(
                    "Bytecode {{ entry: {reflected:?}, bytes: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{stem}.cso\")) }}"
                );
                if index == 0 {
                    writeln!(table, "vertex: {blob}, fragments: &[").unwrap();
                } else {
                    writeln!(table, "({entry:?}, {blob}),").unwrap();
                }
            }
            table.push_str("], };\n");
        }
    }
    std::fs::write(out.join("still_image_bytecode.rs"), table).unwrap();
}

fn translate(
    module: &naga::Module,
    info: &naga::valid::ModuleInfo,
    options: &hlsl::Options,
    stage: ShaderStage,
    entry: &str,
    fragment: &str,
) -> (String, String) {
    // HAL derives fragment linkage before process_overrides compacts the IR.
    let linkage = (stage == ShaderStage::Vertex)
        .then(|| hlsl::FragmentEntryPoint::new(module, fragment).unwrap());
    let (processed, processed_info) = naga::back::pipeline_constants::process_overrides(
        module,
        info,
        Some((stage, entry)),
        &Default::default(),
    )
    .expect("resolve static-image entry point");
    let pipeline = hlsl::PipelineOptions {
        entry_point: Some((stage, entry.into())),
    };
    let mut source = String::new();
    let mut reflection = hlsl::Writer::new(&mut source, options, &pipeline)
        .write(&processed, &processed_info, linkage.as_ref())
        .expect("generate static-image HLSL");
    assert_eq!(reflection.entry_point_names.len(), 1);
    (
        source,
        reflection
            .entry_point_names
            .pop()
            .unwrap()
            .expect("HLSL entry name"),
    )
}

fn options(textures: u32) -> hlsl::Options {
    let target = |register| hlsl::BindTarget {
        space: 0,
        register,
        binding_array_size: None,
        dynamic_storage_buffer_offsets_index: None,
        restrict_indexing: false,
    };
    // DX12 assigns registers per resource class, not by WGSL binding number.
    // Fixed layouts: textures t0..tN, uniform b0, special constants b1, all space0.
    let binding_map = (0..=textures)
        .map(|binding| {
            (
                naga::ResourceBinding { group: 0, binding },
                target(if binding == textures { 0 } else { binding }),
            )
        })
        .collect();
    hlsl::Options {
        shader_model: hlsl::ShaderModel::V5_1,
        binding_map,
        fake_missing_bindings: false,
        special_constants_binding: Some(target(1)),
        immediates_target: None,
        dynamic_storage_buffer_offsets_targets: Default::default(),
        zero_initialize_workgroup_memory: true,
        restrict_indexing: true,
        sampler_heap_target: hlsl::SamplerHeapBindTargets {
            standard_samplers: target(0),
            comparison_samplers: target(2048),
        },
        sampler_buffer_binding_map: Default::default(),
        external_texture_binding_map: Default::default(),
        force_loop_bounding: true,
        task_dispatch_limits: Some(naga::back::TaskDispatchLimits {
            max_mesh_workgroups_per_dim: 0,
            max_mesh_workgroups_total: 0,
        }),
        mesh_shader_primitive_indices_clamp: true,
        ray_query_initialization_tracking: true,
    }
}
