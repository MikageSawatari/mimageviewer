struct LoadBatch {
    signature: Vec<(Uuid, PathBuf, Option<BuiltinCreativeLut>)>,
    rx: mpsc::Receiver<Vec<(Uuid, Result<CubeLutParams, String>)>>,
}

struct ManagedCopyBatch {
    rx: mpsc::Receiver<Vec<(Uuid, Result<CubeLutParams, String>)>>,
}

/// Runtime cache owned by `App`. File reads and `.cube` parsing happen in one
/// background batch whenever the registered entry signature changes.
/// 読み込み済み LUT の不変スナップショット。worker が params から自分で引く。
#[derive(Clone, Debug, Default)]
pub struct CreativeLutSnapshot {
    loaded: HashMap<Uuid, SharedCreativeLut>,
}

impl CreativeLutSnapshot {
    #[cfg(test)]
    pub(crate) fn from_loaded(loaded: HashMap<Uuid, SharedCreativeLut>) -> Self {
        Self { loaded }
    }

    /// params が指す LUT と強度。identity か、その LUT が読み込めていなければ `None`。
    pub fn resolve(
        &self,
        params: &crate::adjustment::AdjustParams,
    ) -> Option<(SharedCreativeLut, f32)> {
        if params.creative_lut.is_identity() {
            return None;
        }
        let lut = self.loaded.get(&params.creative_lut.id?)?;
        Some((Arc::clone(lut), params.creative_lut.strength))
    }
}

#[derive(Default)]
pub struct CreativeLutLibrary {
    loaded: HashMap<Uuid, SharedCreativeLut>,
    errors: HashMap<Uuid, String>,
    managed_migrated: HashSet<Uuid>,
    signature: Vec<(Uuid, PathBuf, Option<BuiltinCreativeLut>)>,
    pending: Option<LoadBatch>,
    managed_copy_pending: Option<ManagedCopyBatch>,
}

impl CreativeLutLibrary {
    pub fn new(entries: &[CreativeLutEntry]) -> Self {
        let mut this = Self::default();
        this.reload(entries);
        this
    }

    pub fn reload(&mut self, entries: &[CreativeLutEntry]) {
        let signature = entry_signature(entries);
        if self.signature == signature
            && self
                .pending
                .as_ref()
                .is_none_or(|pending| pending.signature == signature)
        {
            return;
        }
        self.signature = signature.clone();
        self.loaded
            .retain(|id, _| signature.iter().any(|(entry_id, _, _)| entry_id == id));
        self.errors
            .retain(|id, _| signature.iter().any(|(entry_id, _, _)| entry_id == id));
        self.managed_migrated
            .retain(|id| signature.iter().any(|(entry_id, _, _)| entry_id == id));

        if signature.is_empty() {
            self.pending = None;
            return;
        }

        let (tx, rx) = mpsc::channel();
        let worker_signature = signature.clone();
        let spawned = std::thread::Builder::new()
            .name("creative-lut-loader".to_owned())
            .spawn(move || {
                let results = worker_signature
                    .iter()
                    .map(|(id, path, builtin)| {
                        (
                            *id,
                            builtin
                                .map(build_builtin_creative_lut)
                                .map(Ok)
                                .unwrap_or_else(|| load_registered_cube_file(*id, path)),
                        )
                    })
                    .collect();
                let _ = tx.send(results);
            });
        match spawned {
            Ok(_) => self.pending = Some(LoadBatch { signature, rx }),
            Err(error) => {
                self.pending = None;
                let message = format!("LUTの読み込みスレッドを開始できません: {error}");
                self.errors.extend(
                    signature
                        .into_iter()
                        .map(|(id, _, _)| (id, message.clone())),
                );
            }
        }
        self.start_managed_copy_migration(entries);
    }

    pub fn poll(&mut self, entries: &[CreativeLutEntry], ctx: &egui::Context) -> bool {
        self.reload(entries);
        let mut changed = false;

        let load_result = self.pending.as_ref().map(|pending| pending.rx.try_recv());
        match load_result {
            Some(Ok(results)) => {
                let pending = self.pending.take().expect("checked above");
                if pending.signature == self.signature {
                    let previous_loaded = std::mem::take(&mut self.loaded);
                    self.errors.clear();
                    for (id, result) in results {
                        match result {
                            Ok(lut) => {
                                self.loaded.insert(id, Arc::new(lut));
                            }
                            Err(error) => {
                                if self.managed_migrated.contains(&id)
                                    && let Some(lut) = previous_loaded.get(&id)
                                {
                                    self.loaded.insert(id, Arc::clone(lut));
                                } else {
                                    self.errors.insert(id, error);
                                }
                            }
                        }
                    }
                    changed = true;
                }
            }
            Some(Err(mpsc::TryRecvError::Disconnected)) => {
                self.pending = None;
            }
            Some(Err(mpsc::TryRecvError::Empty)) | None => {}
        }

        let migration_result = self
            .managed_copy_pending
            .as_ref()
            .map(|pending| pending.rx.try_recv());
        match migration_result {
            Some(Ok(results)) => {
                self.managed_copy_pending = None;
                let registered_ids: HashSet<_> = entries.iter().map(|entry| entry.id).collect();
                let mut stale_ids = Vec::new();
                for (id, result) in results {
                    if !registered_ids.contains(&id) {
                        stale_ids.push(id);
                        continue;
                    }
                    match result {
                        Ok(lut) => {
                            self.loaded.insert(id, Arc::new(lut));
                            self.errors.remove(&id);
                            self.managed_migrated.insert(id);
                            changed = true;
                        }
                        Err(error) => crate::logger::log(format!(
                            "creative LUT managed-copy migration failed for {id}: {error}"
                        )),
                    }
                }
                remove_managed_creative_luts_async(stale_ids);
            }
            Some(Err(mpsc::TryRecvError::Disconnected)) => {
                self.managed_copy_pending = None;
            }
            Some(Err(mpsc::TryRecvError::Empty)) | None => {}
        }

        if changed {
            ctx.request_repaint();
        }
        changed
    }

    fn start_managed_copy_migration(&mut self, entries: &[CreativeLutEntry]) {
        if self.managed_copy_pending.is_some() {
            return;
        }
        let user_entries = entries
            .iter()
            .filter(|entry| !entry.is_builtin())
            .map(|entry| (entry.id, entry.path.clone()))
            .collect::<Vec<_>>();
        if user_entries.is_empty() {
            self.managed_copy_pending = None;
            return;
        }

        let (tx, rx) = mpsc::channel();
        let spawned = std::thread::Builder::new()
            .name("creative-lut-managed-copy".to_owned())
            .spawn(move || {
                let results = user_entries
                    .into_iter()
                    .map(|(id, source_path)| (id, ensure_managed_creative_lut(id, &source_path)))
                    .collect();
                let _ = tx.send(results);
            });
        match spawned {
            Ok(_) => {
                self.managed_copy_pending = Some(ManagedCopyBatch { rx });
            }
            Err(error) => {
                crate::logger::log(format!(
                    "creative LUT managed-copy migration thread failed to start: {error}"
                ));
                self.managed_copy_pending = None;
            }
        }
    }

    pub fn get(&self, id: Option<Uuid>) -> Option<SharedCreativeLut> {
        id.and_then(|id| self.loaded.get(&id).cloned())
    }

    /// worker へ渡す読み込み済み LUT の一覧。
    ///
    /// 値は `Arc` なので clone は参照カウントの加算だけ。**解決済みの 1 本ではなく
    /// 一覧を渡す**のは、どの LUT を使うかが params 側で決まり、その params を worker が
    /// 読み直すことがあるため (v3.5.0 レビュー F10)。
    pub fn snapshot(&self) -> CreativeLutSnapshot {
        CreativeLutSnapshot {
            loaded: self.loaded.clone(),
        }
    }

    pub fn error(&self, id: Uuid) -> Option<&str> {
        self.errors.get(&id).map(String::as_str)
    }

    pub fn loaded_ids(&self) -> HashSet<Uuid> {
        self.loaded.keys().copied().collect()
    }

    pub fn video_snapshot(
        &self,
        entries: &[CreativeLutEntry],
        adjustments: &VideoAdjustments,
        preset_slots: &VideoPresetSlots,
    ) -> VideoGradeSnapshot {
        let choices = entries
            .iter()
            .map(|entry| CreativeLutChoice {
                id: entry.id,
                name: entry.name.clone(),
                path: entry
                    .builtin
                    .map(|builtin| format!("組み込みプリセット: {}", builtin.description()))
                    .unwrap_or_else(|| managed_creative_lut_path(entry.id).display().to_string()),
                builtin: entry.is_builtin(),
                loaded: self.loaded.contains_key(&entry.id),
                error: self.errors.get(&entry.id).cloned(),
            })
            .collect::<Vec<_>>()
            .into();
        VideoGradeSnapshot {
            adjustments: adjustments.clone(),
            choices,
            lut: self.get(adjustments.creative_lut.id),
            slots: preset_slots
                .slots
                .iter()
                .map(|slot| slot.as_ref().map(|slot| slot.name.clone()))
                .collect::<Vec<_>>()
                .into(),
        }
    }
}

/// Load one registered entry without mutating or migrating the library.
///
/// The remote adapter owns its parsed-LUT cache and uses this same parser and
/// built-in generator as the desktop library.
pub(crate) fn load_creative_lut_entry(
    entry: &CreativeLutEntry,
) -> Result<SharedCreativeLut, String> {
    let lut = match entry.builtin {
        Some(builtin) => build_builtin_creative_lut(builtin),
        None => load_registered_cube_file(entry.id, &entry.path)?,
    };
    Ok(Arc::new(lut))
}

fn load_registered_cube_file(id: Uuid, source_path: &Path) -> Result<CubeLutParams, String> {
    let managed_path = managed_creative_lut_path(id);
    match std::fs::metadata(&managed_path) {
        Ok(_) => load_cube_file(&managed_path),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => load_cube_file(source_path),
        Err(error) => Err(format!(
            "{} の情報を取得できません: {error}",
            managed_path.display()
        )),
    }
}

fn ensure_managed_creative_lut(id: Uuid, source_path: &Path) -> Result<CubeLutParams, String> {
    let managed_path = managed_creative_lut_path(id);
    match std::fs::metadata(&managed_path) {
        Ok(_) => return load_cube_file(&managed_path),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => {
            return Err(format!(
                "{} の情報を取得できません: {error}",
                managed_path.display()
            ));
        }
    }

    let payload = read_cube_payload(source_path)?;
    write_managed_cube_atomic(&managed_path, &payload.bytes)?;
    Ok(payload.lut)
}

pub struct CreativeLutImport {
    pub entry: CreativeLutEntry,
}

pub fn import_managed_cube_file(path: &Path, id: Uuid) -> Result<CreativeLutImport, String> {
    let payload = read_cube_payload(path)?;
    let target = managed_creative_lut_path(id);
    write_new_managed_cube(&target, &payload.bytes)?;
    Ok(CreativeLutImport {
        entry: CreativeLutEntry::from_loaded_path_with_id(path.to_path_buf(), &payload.lut, id),
    })
}

pub fn managed_creative_lut_dir() -> PathBuf {
    crate::data_dir::get().join("luts")
}

pub fn managed_creative_lut_path(id: Uuid) -> PathBuf {
    managed_creative_lut_dir().join(format!("{id}.cube"))
}

pub fn remove_managed_creative_luts_async(ids: Vec<Uuid>) {
    if ids.is_empty() {
        return;
    }
    let _ = std::thread::Builder::new()
        .name("creative-lut-managed-remove".to_owned())
        .spawn(move || {
            for id in ids {
                if let Err(error) = remove_managed_creative_lut(id)
                    && error.kind() != std::io::ErrorKind::NotFound
                {
                    crate::logger::log(format!(
                        "creative LUT managed copy removal failed for {id}: {error}"
                    ));
                }
            }
        });
}

pub fn remove_managed_creative_lut(id: Uuid) -> std::io::Result<()> {
    std::fs::remove_file(managed_creative_lut_path(id))
}

fn entry_signature(
    entries: &[CreativeLutEntry],
) -> Vec<(Uuid, PathBuf, Option<BuiltinCreativeLut>)> {
    entries
        .iter()
        .map(|entry| (entry.id, entry.path.clone(), entry.builtin))
        .collect()
}

fn build_builtin_creative_lut(builtin: BuiltinCreativeLut) -> CubeLutParams {
    const SIZE: usize = 17;
    let mut table = Vec::with_capacity(SIZE * SIZE * SIZE);
    for b in 0..SIZE {
        for g in 0..SIZE {
            for r in 0..SIZE {
                let denominator = (SIZE - 1) as f32;
                let input = [
                    r as f32 / denominator,
                    g as f32 / denominator,
                    b as f32 / denominator,
                ];
                table.push(apply_builtin_look(builtin, input));
            }
        }
    }
    CubeLutParams {
        name: builtin.name().to_owned(),
        size: SIZE,
        domain_min: [0.0; 3],
        domain_max: [1.0; 3],
        table,
        strength: 1.0,
    }
}

fn apply_builtin_look(builtin: BuiltinCreativeLut, rgb: [f32; 3]) -> [f32; 3] {
    let clamp = |value: f32| value.clamp(0.0, 1.0);
    let contrast = |value: f32, amount: f32| clamp((value - 0.5) * amount + 0.5);
    let saturate = |color: [f32; 3], amount: f32| {
        let luma = color[0] * 0.299 + color[1] * 0.587 + color[2] * 0.114;
        [
            clamp(luma + (color[0] - luma) * amount),
            clamp(luma + (color[1] - luma) * amount),
            clamp(luma + (color[2] - luma) * amount),
        ]
    };
    match builtin {
        BuiltinCreativeLut::WarmFilm => {
            let base = saturate(
                [
                    contrast(rgb[0], 1.06),
                    contrast(rgb[1], 1.04),
                    contrast(rgb[2], 1.02),
                ],
                0.96,
            );
            let light = (base[0] * 0.299 + base[1] * 0.587 + base[2] * 0.114).sqrt();
            [
                clamp(base[0] + 0.030 * light + 0.006),
                clamp(base[1] + 0.010 * light),
                clamp(base[2] - 0.028 * light),
            ]
        }
        BuiltinCreativeLut::CoolFade => {
            let faded = [
                0.035 + rgb[0] * 0.91,
                0.040 + rgb[1] * 0.92,
                0.055 + rgb[2] * 0.93,
            ];
            let base = saturate(faded, 0.88);
            [
                clamp(base[0] * 0.97),
                clamp(base[1] * 1.005),
                clamp(base[2] * 1.035 + 0.008),
            ]
        }
        BuiltinCreativeLut::TealOrange => {
            let base = saturate(
                [
                    contrast(rgb[0], 1.08),
                    contrast(rgb[1], 1.08),
                    contrast(rgb[2], 1.08),
                ],
                1.08,
            );
            let luma = clamp(base[0] * 0.299 + base[1] * 0.587 + base[2] * 0.114);
            let shadow = (1.0 - luma).powf(1.6);
            let highlight = luma.powf(1.6);
            [
                clamp(base[0] + 0.060 * highlight - 0.024 * shadow),
                clamp(base[1] + 0.024 * shadow + 0.008 * highlight),
                clamp(base[2] + 0.052 * shadow - 0.045 * highlight),
            ]
        }
        BuiltinCreativeLut::Vintage => {
            let faded = [
                0.055 + rgb[0] * 0.88,
                0.050 + rgb[1] * 0.87,
                0.042 + rgb[2] * 0.84,
            ];
            let base = saturate(faded, 0.72);
            let sepia = [
                clamp(base[0] * 0.393 + base[1] * 0.769 + base[2] * 0.189),
                clamp(base[0] * 0.349 + base[1] * 0.686 + base[2] * 0.168),
                clamp(base[0] * 0.272 + base[1] * 0.534 + base[2] * 0.131),
            ];
            [
                clamp(base[0] * 0.86 + sepia[0] * 0.14),
                clamp(base[1] * 0.86 + sepia[1] * 0.14),
                clamp(base[2] * 0.86 + sepia[2] * 0.14),
            ]
        }
        BuiltinCreativeLut::MonochromeFilm => {
            let luma = rgb[0] * 0.299 + rgb[1] * 0.587 + rgb[2] * 0.114;
            let value = clamp(contrast(luma, 1.12) * 0.98 + 0.012);
            [value; 3]
        }
    }
}

struct CubePayload {
    lut: CubeLutParams,
    bytes: Vec<u8>,
}

fn read_cube_payload(path: &Path) -> Result<CubePayload, String> {
    let metadata = std::fs::metadata(path)
        .map_err(|error| format!("{} の情報を取得できません: {error}", path.display()))?;
    if metadata.len() > MAX_CUBE_FILE_BYTES {
        return Err(format!(
            "LUTファイルが大きすぎます（上限 {} MiB）",
            MAX_CUBE_FILE_BYTES / 1024 / 1024
        ));
    }
    let bytes = std::fs::read(path)
        .map_err(|error| format!("{} を読み込めません: {error}", path.display()))?;
    if bytes.len() as u64 > MAX_CUBE_FILE_BYTES {
        return Err(format!(
            "LUTファイルが大きすぎます（上限 {} MiB）",
            MAX_CUBE_FILE_BYTES / 1024 / 1024
        ));
    }
    let text = std::str::from_utf8(&bytes)
        .map_err(|error| format!("{} はUTF-8の.cubeではありません: {error}", path.display()))?;
    let fallback = path
        .file_stem()
        .and_then(|value| value.to_str())
        .unwrap_or("LUT");
    let lut = local_adjust_core::parse_cube_lut(text, fallback)?;
    Ok(CubePayload { lut, bytes })
}

fn write_new_managed_cube(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let parent = path
        .parent()
        .ok_or_else(|| "LUTの保存先ディレクトリを決定できません。".to_owned())?;
    std::fs::create_dir_all(parent)
        .map_err(|error| format!("{} を作成できません: {error}", parent.display()))?;
    let mut output = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|error| format!("{} を作成できません: {error}", path.display()))?;
    if let Err(error) = output.write_all(bytes).and_then(|_| output.sync_data()) {
        drop(output);
        let _ = std::fs::remove_file(path);
        return Err(format!("{} へ保存できません: {error}", path.display()));
    }
    Ok(())
}

fn write_managed_cube_atomic(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let parent = path
        .parent()
        .ok_or_else(|| "LUTの保存先ディレクトリを決定できません。".to_owned())?;
    std::fs::create_dir_all(parent)
        .map_err(|error| format!("{} を作成できません: {error}", parent.display()))?;
    let temp_path = parent.join(format!(".{}.tmp", Uuid::new_v4()));
    write_new_managed_cube(&temp_path, bytes)?;
    if let Err(error) = std::fs::rename(&temp_path, path) {
        let _ = std::fs::remove_file(&temp_path);
        return Err(format!("{} を確定できません: {error}", path.display()));
    }
    Ok(())
}

pub fn load_cube_file(path: &Path) -> Result<CubeLutParams, String> {
    read_cube_payload(path).map(|payload| payload.lut)
}

pub fn apply_to_color_image(
    source: &egui::ColorImage,
    lut: &CubeLutParams,
    strength: f32,
) -> egui::ColorImage {
    let strength = strength.clamp(0.0, 1.0);
    if strength <= f32::EPSILON || !lut.is_loaded() {
        return source.clone();
    }
    let pixels = source
        .pixels
        .iter()
        .map(|pixel| {
            let [r, g, b, a] = pixel.to_srgba_unmultiplied();
            let input = [r as f32 / 255.0, g as f32 / 255.0, b as f32 / 255.0];
            let output = local_adjust_core::sample_cube_lut(lut, input);
            let mix = |original: f32, graded: f32| {
                ((original + (graded - original) * strength).clamp(0.0, 1.0) * 255.0).round() as u8
            };
            egui::Color32::from_rgba_unmultiplied(
                mix(input[0], output[0]),
                mix(input[1], output[1]),
                mix(input[2], output[2]),
                a,
            )
        })
        .collect();
    egui::ColorImage::new(source.size, pixels)
}

