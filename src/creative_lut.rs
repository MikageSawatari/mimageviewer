//! Creative 3D LUT registration, asynchronous loading, and CPU application.
//!
//! Registered entries keep the original user-selected `.cube` path for display
//! and legacy migration, while the app-owned copy lives under
//! `<data_dir>/luts/<entry UUID>.cube`. Parsing and managed-file I/O are always
//! performed on worker threads; the UI and video-presenter threads only use
//! already parsed immutable tables.

use eframe::egui;
use local_adjust_core::CubeLutParams;
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::{Arc, mpsc};
use uuid::Uuid;

const MAX_CUBE_FILE_BYTES: u64 = 128 * 1024 * 1024;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CreativeLutEntry {
    pub id: Uuid,
    pub name: String,
    pub path: PathBuf,
    #[serde(default)]
    pub builtin: Option<BuiltinCreativeLut>,
}

impl CreativeLutEntry {
    pub fn from_loaded_path_with_id(path: PathBuf, lut: &CubeLutParams, id: Uuid) -> Self {
        let mut entry = Self::from_loaded_path(path, lut);
        entry.id = id;
        entry
    }

    pub fn from_loaded_path(path: PathBuf, lut: &CubeLutParams) -> Self {
        let file_stem = path
            .file_stem()
            .and_then(|value| value.to_str())
            .map(str::trim)
            .filter(|value| !value.is_empty());
        // `.cube` generators frequently write the same generic TITLE
        // ("Generated by Resolve"など) into a whole pack. The source filename
        // is the useful, normally unique display name; TITLE remains parser
        // metadata and is only a fallback for a path without a usable stem.
        let name = file_stem
            .map(str::to_owned)
            .or_else(|| {
                let title = lut.name.trim();
                (!title.is_empty()).then(|| title.to_owned())
            })
            .unwrap_or_else(|| "LUT".to_owned());
        Self {
            id: Uuid::new_v4(),
            name,
            path,
            builtin: None,
        }
    }

    pub fn is_builtin(&self) -> bool {
        self.builtin.is_some()
    }

    pub fn managed_path(&self) -> Option<PathBuf> {
        (!self.is_builtin()).then(|| managed_creative_lut_path(self.id))
    }

    /// Repair names written by the old importer, which preferred a generic
    /// Resolve TITLE over the source filename. User-renamed entries are left
    /// untouched.
    pub fn repair_legacy_generated_name(&mut self) {
        if self.builtin.is_some() || !is_generic_generated_title(&self.name) {
            return;
        }
        if let Some(file_stem) = self
            .path
            .file_stem()
            .and_then(|value| value.to_str())
            .map(str::trim)
            .filter(|value| !value.is_empty())
        {
            self.name = file_stem.to_owned();
        }
    }
}

fn is_generic_generated_title(name: &str) -> bool {
    let name = name.trim();
    name.eq_ignore_ascii_case("Generated by Resolve")
        || name.eq_ignore_ascii_case("Generated by DaVinci Resolve")
}

/// Stable built-in creative looks. These are generated as ordinary 17³ LUT
/// tables, so the CPU still-image path and D3D11 video path use exactly the
/// same sampler as user-provided `.cube` files.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BuiltinCreativeLut {
    WarmFilm,
    CoolFade,
    TealOrange,
    Vintage,
    MonochromeFilm,
}

impl BuiltinCreativeLut {
    pub const ALL: [Self; 5] = [
        Self::WarmFilm,
        Self::CoolFade,
        Self::TealOrange,
        Self::Vintage,
        Self::MonochromeFilm,
    ];

    pub fn id(self) -> Uuid {
        let suffix = match self {
            Self::WarmFilm => 1,
            Self::CoolFade => 2,
            Self::TealOrange => 3,
            Self::Vintage => 4,
            Self::MonochromeFilm => 5,
        };
        Uuid::from_u128(0x6d49_564c_5554_4000_8000_0000_0000_0000 | suffix)
    }

    pub fn name(self) -> &'static str {
        match self {
            Self::WarmFilm => "ウォームフィルム",
            Self::CoolFade => "クールフェード",
            Self::TealOrange => "シネマティック（Teal & Orange）",
            Self::Vintage => "ヴィンテージ",
            Self::MonochromeFilm => "モノクロフィルム",
        }
    }

    pub fn description(self) -> &'static str {
        match self {
            Self::WarmFilm => "暖色寄りのハイライトと穏やかなフィルム調コントラスト",
            Self::CoolFade => "黒を少し浮かせた、青みのある低彩度ルック",
            Self::TealOrange => "シャドウを青緑、ハイライトを暖色へ寄せるシネマ調",
            Self::Vintage => "彩度とコントラストを抑えた、褪色した写真風",
            Self::MonochromeFilm => "輝度を保ちながら引き締める白黒フィルム調",
        }
    }
}

pub fn builtin_creative_lut_entries() -> Vec<CreativeLutEntry> {
    BuiltinCreativeLut::ALL
        .into_iter()
        .map(|builtin| CreativeLutEntry {
            id: builtin.id(),
            name: builtin.name().to_owned(),
            path: PathBuf::new(),
            builtin: Some(builtin),
        })
        .collect()
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct CreativeLutSelection {
    pub id: Option<Uuid>,
    /// Original pixels and LUT output are linearly mixed by this value.
    pub strength: f32,
}

impl Default for CreativeLutSelection {
    fn default() -> Self {
        Self {
            id: None,
            strength: 1.0,
        }
    }
}

impl CreativeLutSelection {
    pub fn is_identity(&self) -> bool {
        self.id.is_none() || self.strength <= f32::EPSILON
    }

    pub fn sanitize(&mut self) {
        self.strength = self.strength.clamp(0.0, 1.0);
    }
}

/// Video preview adjustments. These are viewer-wide and intentionally carry
/// only the image panel's tone controls plus creative LUT selection.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct VideoAdjustments {
    pub brightness: f32,
    pub contrast: f32,
    pub gamma: f32,
    pub saturation: f32,
    pub temperature: f32,
    pub black_point: u8,
    pub white_point: u8,
    pub midtone: f32,
    pub creative_lut: CreativeLutSelection,
}

impl Default for VideoAdjustments {
    fn default() -> Self {
        Self {
            brightness: 0.0,
            contrast: 0.0,
            gamma: 1.0,
            saturation: 0.0,
            temperature: 0.0,
            black_point: 0,
            white_point: 255,
            midtone: 1.0,
            creative_lut: CreativeLutSelection::default(),
        }
    }
}

impl VideoAdjustments {
    pub fn is_color_identity(&self) -> bool {
        self.brightness == 0.0
            && self.contrast == 0.0
            && self.gamma == 1.0
            && self.saturation == 0.0
            && self.temperature == 0.0
            && self.black_point == 0
            && self.white_point == 255
            && self.midtone == 1.0
    }

    pub fn is_identity(&self) -> bool {
        self.is_color_identity() && self.creative_lut.is_identity()
    }

    pub fn sanitize(&mut self) {
        self.brightness = self.brightness.clamp(-100.0, 100.0);
        self.contrast = self.contrast.clamp(-100.0, 100.0);
        self.gamma = self.gamma.clamp(0.2, 5.0);
        self.saturation = self.saturation.clamp(-100.0, 100.0);
        self.temperature = self.temperature.clamp(-100.0, 100.0);
        if self.white_point <= self.black_point {
            self.white_point = self.black_point.saturating_add(1);
            if self.white_point == self.black_point {
                self.black_point = self.white_point.saturating_sub(1);
            }
        }
        self.midtone = self.midtone.clamp(0.1, 10.0);
        self.creative_lut.sanitize();
    }
}

